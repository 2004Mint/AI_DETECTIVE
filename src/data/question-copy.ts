/**
 * 取某个题材的文案；未登记的题材返回兜底文案，
 * 并把题材标签设为原始键名，方便一眼看出是新题材。
 */
export function copyForCategory(key: string): CategoryCopy {
  const hit = CATEGORY_COPY[key]
  if (hit) return hit
  return { ...DEFAULT_CATEGORY_COPY, label: key }
}
