export interface CategoryCopy {
  /** 游戏中展示的题材标签 */
  label: string
  /** 真实图那一侧的称呼（照片题材叫「真实照片」，绘画题材叫「人类画作」） */
  realLabel: string
  /** 题目角标文案池 */
  titles: readonly string[]
  /**
   * 「AI 破绽」讲解文案池
   * 注意：结果弹窗目前已按需求移除知识卡，这组文案**暂不展示**，
   * 保留在此以便随时恢复（恢复方式：ResultModal 里把 `question.explanation` 渲染出来即可）。
   */
  explanations: readonly string[]
}

